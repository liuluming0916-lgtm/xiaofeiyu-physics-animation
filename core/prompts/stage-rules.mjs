/**
 * 各阶段的**公式规范**（第 9 期 · 用户裁决：把规范从世界书搬回阶段提示词）。
 *
 * ── 为什么搬回来 ──
 * 世界书是按**槽位**分发的（只有 `solve` / `scene_code` 两档），而生产链有 5 个阶段，
 * 其中 3 个阶段共用 `solve` 槽 ⇒ "只跟代码有关"的规矩（`RETURN` / `readouts` / 时间轴）
 * 被无差别灌进了解题、分步、答案三个阶段。用户的原话是"无脑复读"。
 *
 * README §9.6 早就把界限写清楚了：**阶段契约 ≠ 条件知识**。
 *   · 规范（每题都成立、与命中无关）→ 属于**阶段指令**，这里；
 *   · 知识（看题才唤醒的元件画法、题型提醒）→ 属于**世界书**。
 * 所以这批规范搬回提示词，世界书只留"条件知识"（30 张元件卡 + 约定 + 总览）。
 *
 * ── 搬哪几条（10 张卡的归属，逐条交代，不留悬空）──
 *   · 进「解题」6 条：符号单位正方向 / 矢量与分量 / 公式与数值写法 / 量纲与极限 / 守恒与过程式 / 临界与极值
 *     —— 它们讲的是"落笔方式"，且原先**只**出现在世界书，解题阶段一命中不到就等于没写；
 *   · 进「动画代码」1 条：边界连续性（位置连续、速度只许有冲量时跳变）→ 并进速查表的一条；
 *   · **本来就重复、直接删** 3 条：
 *       - 时间轴规范（`breakdown` 的正文早已写了"无缝、有序、末步 = 总时长、边界对准事件"）；
 *       - 答案结构规范（`ANSWERS` 与 C7 已删，程序不再要求结构）；
 *       - 命名与读数一致（`readouts` 由 analysis 生成，AI 不再手写）。
 *
 * ⚠ 这些文字进 `prompt.system`（**条件段**），不是 `ROLE_AND_OUTPUT_RULES`（固定前缀）——
 *   所以 `promptHash` 不变，缓存不受影响；而且它们只在**自己那个阶段**出现一次。
 */

/** 解题阶段的 5 条规范（顺序即"读下去的顺序"：先定义，再动笔，再写守恒） */
export const SOLVE_RULES = Object.freeze([
  [
    '## 规范·符号、单位与正方向',
    '- 一维问题先声明正方向，之后一律用**带符号标量**：向右为正，则向左的速度写负值。',
    '- 符号固定：位移 x、速度 v、初速 v0、加速度 a、时间 t、间隔 T；力 G/N/f/F_T；能 Ek/Ep/W/P/Q；电磁 q/E/phi/U/I/R/B/Phi。',
    '- 单位一律 SI。g 取题面给定值；题面没给就取 10 m/s²。',
    '- 角度在解析里写度数。非常用单位（cmHg、km/h、eV）先换算成 SI 再代入。',
  ].join('\n'),
  [
    '## 规范·矢量与分量',
    '- 矢量先交代**大小 + 方向**（与正方向的夹角，或两个正交分量），再参与运算。',
    '- 分解按已声明的两个正交轴投影：沿轴用 cos、垂直轴用 sin；两轴全程不换。',
    '- 合成写成矢量式再取大小：v = √(vx² + vy²)，方向 tanθ = vy / vx。',
  ].join('\n'),
  [
    '## 规范·公式与数值的写法',
    '- 先推**符号表达式**，再代数值。',
    '- 数值取 2–3 位有效数字，与题面数据的精度对齐；中间量保留符号，最后一步才代入。',
    '- 代入的数值与题面逐字一致。',
  ].join('\n'),
  [
    '## 规范·守恒式与过程式的写法',
    '- 守恒式三步走：**先声明系统与正方向** → 写守恒量（初态 = 末态）→ 再代入具体量。',
    '- 过程式（动能定理、动量定理）先写"谁对谁做功 / 谁给谁冲量"，再写等式。',
    '- 守恒不成立时（有外力、有摩擦）改用含外功的式子，并说明差额补在哪一项。',
  ].join('\n'),
  [
    '## 规范·临界与极值',
    '- 临界点写成**某个力或约束等于零（或取到极值）的等式**：N = 0（脱离/过顶）、f = f_max（刚要滑）、T = 0（绳刚松）。',
    '- 先写临界条件式，再解出待求量；结论里说清取到极值的时刻或位置，并说明为什么在这里取到。',
  ].join('\n'),
]);

/** 按阶段取规范文本（目前只有解题阶段有规范） */
export function rulesForStage(stage) {
  return stage === 'solve' ? SOLVE_RULES : [];
}
