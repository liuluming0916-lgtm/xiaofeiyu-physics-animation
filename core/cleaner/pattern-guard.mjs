/**
 * 灾难性回溯形态检测（**纯函数、零依赖**）。
 *
 * 为什么单独一个文件：它同时被两边用 —— 运行时清洗器（`regex-rules.mjs`）与
 * 保存时的策略校验（`policy.mjs`）。放在 `regex-rules.mjs` 里会让 `policy ⇄ regex-rules`
 * 形成循环 import。循环在本仓并非不能用（函数声明有提升），但**能避免就避免**：
 * 一次偶然的顶层调用就会把"循环"变成"undefined 不是函数"的夜间事故。
 *
 * 检测已知的三类构造：
 *   ① 量词套量词：`(a+)+` / `(a*)*` / `(a+)*`
 *   ② 量词套在可空的择一上：`(a|a)*` / `(a|)+`
 *   ③ 相邻重复的贪婪通配：`.*.*` / `(.+)+`
 *
 * ⚠ 这是**启发式**，不是完备判定（完备判定不可行）。因此它的定位是"拒绝已知坏形态"，
 *   **不是"证明剩下的都安全"** —— 这一点在文档与注释里都写清楚，不夸大。
 *   真正的墙钟超时仍然没有（本沙箱禁子进程管道），见 `regex-rules.mjs` 顶部的取舍说明。
 *
 * @param {string} pattern 正则源文本
 * @returns {{ safe: boolean, reason?: string }}
 */
export function detectCatastrophicPattern(pattern) {
  const p = String(pattern ?? '');

  // ① 分组被量词修饰，且组内本身以量词结尾：  (...+)+  (...*)*  (...+)*
  if (/\([^()]*[*+][^()]*\)\s*[*+]/.test(p)) {
    return { safe: false, reason: '分组内已有量词、分组外又加量词（如 (a+)+），会灾难性回溯' };
  }
  // ② 分组是"可空的择一"又被量词修饰： (a|a)*  (a|)*
  if (/\((?:[^()|]*\|[^()|]*)*\)\s*[*+]/.test(p) && /\([^()]*\|[^()]*\)/.test(p)) {
    return { safe: false, reason: '对"择一"分组使用量词（如 (a|b)*）在重复分支上会灾难性回溯' };
  }
  // ③ 相邻的贪婪通配重复：  .*.  .*.*  .+.+
  if (/(\.\*|\.\+)\s*(\.\*|\.\+)/.test(p)) {
    return { safe: false, reason: '相邻的贪婪通配（如 .*.*）会灾难性回溯' };
  }
  return { safe: true };
}
